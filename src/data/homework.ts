/**
 * «Домашка» — мини-проект в конце каждого раздела. Ученик пишет промпт (или собирает его из блоков),
 * симулированный ИИ (src/homework/sims.ts, без API) собирает результат, превью показывает его вживую,
 * а чек-лист отмечает выполненные требования.
 */

export type BlockColor = 'brand' | 'coral' | 'teal' | 'deep' | 'amber' | 'grey'

export interface PromptBlock {
  /** Подпись группы: «Роль», «Секции», «Ошибка»… */
  group: string
  color: BlockColor
  /** Короткая подпись на чипе */
  label: string
  /** Текст, который вставляется в промпт */
  text: string
  /** «Пустые слова» — не добавляют информации; Бипи объяснит почему */
  weak?: boolean
}

export interface Requirement {
  id: string
  label: string
  /** Подсказка Бипи, если требование не выполнено */
  hint: string
}

export type PreviewAction = 'viewMobile' | 'copyError' | 'copyCode' | 'addTask' | 'submitForm' | 'openSite'
export type SolutionStep = { block: string } | { type: string } | { send: true } | { action: PreviewAction }

export interface HomeworkDef {
  id: string
  unitId: string
  num: number
  /** Короткое имя (узел на пути, тир-прогресс) */
  short: string
  /** Задание крупно: «Собери лендинг кофейни» */
  title: string
  brief: string
  /** Первая реплика Бипи */
  intro: string
  badge: { emoji: string; name: string }
  requirements: Requirement[]
  blocks: PromptBlock[]
  /** Подсказки для уточняющих промптов (после первого ответа) */
  followUps: string[]
  placeholder: string
  /** Есть переключатель «телефон / компьютер» в превью */
  devices?: boolean
  /** «Правильный путь» для скриптов проверки: нажать блоки, дописать текст, отправить, сделать что-то в превью */
  solution: SolutionStep[]
  /** Пример расплывчатого промпта (для проверки: он не должен засчитываться) */
  vague: string
}

